"""Regenerate the backend's Python lock files from requirements.in / requirements-dev.in.

Run from the repository root or backend/:
    py -3.13 scripts/lock_python.py

It builds two throw-away virtual environments, installs the direct dependencies into each, and
writes the exact resolved versions with `pip freeze`:
    backend/requirements.txt      — runtime packages (used by the production image)
    backend/requirements-dev.txt  — "-r requirements.txt" + the extra dev/test packages
Commit both files. Install with: .venv/Scripts/python -m pip install -r requirements-dev.txt
"""

from __future__ import annotations

import subprocess
import sys
import tempfile
import venv
from pathlib import Path

BACKEND = Path(__file__).resolve().parent.parent / "backend"
HEADER = "# GENERATED by scripts/lock_python.py from {src} — do not edit by hand.\n"


def freeze(requirement_files: list[Path]) -> dict[str, str]:
    """Install the given requirement files into a fresh venv and return {name: 'name==version'}."""
    with tempfile.TemporaryDirectory() as tmp:
        venv.create(tmp, with_pip=True)
        python = Path(tmp) / ("Scripts/python.exe" if sys.platform == "win32" else "bin/python")
        args = [str(python), "-m", "pip", "install", "--quiet", "--disable-pip-version-check"]
        for req in requirement_files:
            args += ["-r", str(req)]
        subprocess.run(args, check=True)
        out = subprocess.run(
            [str(python), "-m", "pip", "freeze", "--all", "--exclude", "pip", "--exclude-editable"],
            check=True,
            capture_output=True,
            text=True,
        ).stdout
    pins: dict[str, str] = {}
    for line in out.splitlines():
        if "==" in line:
            pins[line.split("==", 1)[0].lower()] = line.strip()
    return pins


def main() -> None:
    runtime = freeze([BACKEND / "requirements.in"])
    everything = freeze([BACKEND / "requirements.in", BACKEND / "requirements-dev.in"])

    conflicts = [n for n, pin in runtime.items() if everything.get(n) not in (None, pin)]
    if conflicts:
        sys.exit(f"Dev tools change runtime versions, resolve manually: {conflicts}")

    (BACKEND / "requirements.txt").write_text(
        HEADER.format(src="requirements.in") + "\n".join(sorted(runtime.values())) + "\n",
        encoding="utf-8",
    )
    dev_only = sorted(pin for name, pin in everything.items() if name not in runtime)
    (BACKEND / "requirements-dev.txt").write_text(
        HEADER.format(src="requirements-dev.in")
        + "-r requirements.txt\n"
        + "\n".join(dev_only)
        + "\n",
        encoding="utf-8",
    )
    print(f"Locked {len(runtime)} runtime and {len(dev_only)} dev-only packages.")


if __name__ == "__main__":
    main()
