"""Where uploaded media lives (docs/development/ENVIRONMENT_VARIABLES.md: STORAGE_BACKEND).

* `local`: files under MEDIA_ROOT, served by the app at `/media/...` (development, single server).
* `s3`: any S3-compatible bucket (Supabase Storage, Cloudflare R2, AWS S3) with public-read URLs
  under S3_PUBLIC_BASE_URL.

Keys are always generated by the server (random ids), never taken from the uploader.
"""

from __future__ import annotations

import re
from pathlib import Path
from typing import Any, Protocol

from app.core.config import BACKEND_DIR, Settings

_KEY_RE = re.compile(r"^[a-z0-9][a-z0-9/_.-]{0,200}$")


class Storage(Protocol):
    def save(self, key: str, data: bytes, content_type: str) -> str:
        """Store bytes under `key` and return the public URL."""

    def delete(self, key: str) -> None:
        """Remove an object (missing objects are ignored)."""


def _check_key(key: str) -> str:
    if not _KEY_RE.match(key) or ".." in key:
        raise ValueError(f"Unsafe storage key {key!r}")
    return key


class LocalStorage:
    def __init__(self, root: Path, base_url: str = "/media") -> None:
        self.root = root
        self.base_url = base_url.rstrip("/")

    def save(self, key: str, data: bytes, content_type: str) -> str:
        path = self.root / _check_key(key)
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)
        return f"{self.base_url}/{key}"

    def delete(self, key: str) -> None:
        path = self.root / _check_key(key)
        path.unlink(missing_ok=True)


class S3Storage:
    def __init__(self, settings: Settings, client: Any | None = None) -> None:
        if client is None:
            import boto3

            client = boto3.client(
                "s3",
                endpoint_url=settings.s3_endpoint_url or None,
                region_name=settings.s3_region or None,
                aws_access_key_id=settings.s3_access_key_id,
                aws_secret_access_key=settings.s3_secret_access_key.get_secret_value(),
            )
        self.client = client
        self.bucket = settings.s3_bucket
        self.public_base = settings.s3_public_base_url.rstrip("/")

    def save(self, key: str, data: bytes, content_type: str) -> str:
        self.client.put_object(
            Bucket=self.bucket,
            Key=_check_key(key),
            Body=data,
            ContentType=content_type,
            CacheControl="public, max-age=31536000, immutable",
        )
        return f"{self.public_base}/{key}"

    def delete(self, key: str) -> None:
        self.client.delete_object(Bucket=self.bucket, Key=_check_key(key))


def media_root(settings: Settings) -> Path:
    root = Path(settings.media_root)
    return root if root.is_absolute() else BACKEND_DIR / root


def make_storage(settings: Settings) -> Storage:
    if settings.storage_backend == "s3":
        return S3Storage(settings)
    return LocalStorage(media_root(settings))
